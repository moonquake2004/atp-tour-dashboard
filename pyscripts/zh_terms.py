def country_zh(code: str) -> str:
    """Chinese name for a country code, falling back to the code itself."""
    if not code:
        return ""
    return COUNTRY_ZH.get(str(code).upper(), "")


def _fold(value) -> str:
    """Strip combining marks so accented Latin names match ASCII dictionary keys."""
    text = unicodedata.normalize("NFD", str(value or ""))
    return "".join(ch for ch in text if unicodedata.category(ch) != "Mn")


def city_fallback(city) -> str:
    key = _fold(city).upper().strip()
    if key and key in CITY_ZH:
        return f"{CITY_ZH[key]}公开赛"
    return ""


def tournament_zh(raw_name, city=None) -> str:
    """
    Look up a Chinese name for a tournament label.

    The match log stores names in Title Case with occasional level suffixes
    ("Madrid 1000", "Us Open", "Paris 125"), so lookup is normalised: uppercase,
    strip a leading tour word and any trailing level number, then try the curated
    dictionary, then the city dictionary, then a city embedded in the name.
    """
    raw = str(raw_name or "").strip()
    if not raw:
        return city_fallback(city)

    upper = _fold(raw).upper()
    candidates = [upper]

    stripped = re.sub(r"\s*(WTA|ITF|WTT)?\s*(1000|500|250|125)\s*$", "", upper, flags=re.I).strip()
    if stripped != upper:
        candidates.append(stripped)
    candidates.append(re.sub(r"^(WTA|ITF|WTT)\s+", "", upper))

    # "Bjk Cup Qualifiers", "Bjk-semifinals", "Bjk Cup- Final" are all the same
    # team competition; the feed abbreviates it inconsistently.
    if upper.startswith("BJK"):
        if re.search(r"QUALIF", upper):
            return TOURNAMENT_ZH["BILLIE JEAN KING CUP QUALIFIERS"]
        if re.search(r"FINAL", upper) and not re.search(r"SEMI", upper):
            return TOURNAMENT_ZH["BILLIE JEAN KING CUP FINALS"]
        if re.search(r"SEMI", upper):
            return "比利·简·金杯半决赛"
        return TOURNAMENT_ZH["BILLIE JEAN KING CUP"]

    for candidate in candidates:
        if candidate in TOURNAMENT_ZH:
            return TOURNAMENT_ZH[candidate]
    for candidate in candidates:
        if candidate in CITY_ZH:
            return f"{CITY_ZH[candidate]}公开赛"
    # Last resort: a known city embedded anywhere in the label.
    for city_name, zh_name in CITY_ZH.items():
        if city_name in upper:
            return f"{zh_name}公开赛"
    return city_fallback(city)


def player_zh_fallback(english_name: str) -> str:
    """Chinese transliteration for a player the structured sources do not cover."""
    if not english_name:
        return ""
    raw = str(english_name).strip()
    if raw in PLAYER_ZH:
        return PLAYER_ZH[raw]
    folded = re.sub(r"\s+", " ", raw).lower()
    for key, value in PLAYER_ZH.items():
        if key.lower() == folded:
            return value
    return ""


