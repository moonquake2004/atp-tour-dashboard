_CJK = re.compile(r"[\u4e00-\u9fff]")


def has_cjk(value) -> bool:
    return bool(_CJK.search(str(value or "")))


def to_simplified(strings, *, batch: int = 120, cache_file: Path | None = None) -> dict:
    """
    Convert strings to Simplified Chinese with the MediaWiki variant converter.

    The converter is a shared public endpoint and rate-limits aggressively, so
    results are cached across runs and requests are spaced with backoff.  The
    request must be a POST: a 120-name batch overflows the URL length limit with
    GET (HTTP 414).
    """
    out: dict = {}
    unique = [s for s in dict.fromkeys(strings) if s and has_cjk(s)]

    cache: dict = {}
    if cache_file and Path(cache_file).exists():
        try:
            cache = json.loads(Path(cache_file).read_text(encoding="utf-8"))
        except (json.JSONDecodeError, OSError):
            cache = {}

    for value in unique:
        if value in cache:
            out[value] = cache[value]

    pending = [s for s in unique if s not in cache]

    for start in range(0, len(pending), batch):
        chunk = pending[start:start + batch]
        body = urllib.parse.urlencode(
            {
                "action": "parse",
                "text": " | ".join(chunk),
                "contentmodel": "wikitext",
                "prop": "text",
                "format": "json",
                "variant": "zh-hans",
            }
        ).encode("utf-8")

        done = False
        for attempt in range(4):
            if attempt:
                time.sleep(3 * attempt)
            try:
                req = urllib.request.Request(
                    "https://zh.wikipedia.org/w/api.php",
                    data=body,
                    headers={
                        "User-Agent": WIKI_UA,
                        "Content-Type": "application/x-www-form-urlencoded",
                    },
                )
                with urllib.request.urlopen(req, timeout=60, context=SSL_CONTEXT) as resp:
                    data = json.loads(resp.read().decode("utf-8"))
                converted = re.sub(r"<[^>]+>", "", ((data.get("parse") or {}).get("text") or {}).get("*", "")).strip()
                parts = [p.strip() for p in converted.split("|")]
                for index, original in enumerate(chunk):
                    value = parts[index] if index < len(parts) and parts[index] else original
                    out[original] = value
                    cache[original] = value
                done = True
                break
            except Exception as err:  # noqa: BLE001
                if attempt == 3:
                    log("zh", f"  ! variant conversion failed after 4 attempts ({err}); keeping original")
                    for original in chunk:
                        out[original] = original
        if not done:
            pass
        if start + batch < len(pending):
            time.sleep(1.2)

    if cache_file:
        try:
            Path(cache_file).parent.mkdir(parents=True, exist_ok=True)
            Path(cache_file).write_text(json.dumps(cache, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
        except OSError:
            pass

    for value in strings:
        if value and value not in out:
            out[value] = value
    return out


