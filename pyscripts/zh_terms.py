def sparql(query: str, *, retries: int = 3):
    """Run a SPARQL query against Wikidata and return the bindings."""
    url = "https://query.wikidata.org/sparql?" + urllib.parse.urlencode(
        {"query": query, "format": "json"}
    )
    for attempt in range(retries + 1):
        if attempt:
            time.sleep(2 * attempt)
        try:
            req = urllib.request.Request(
                url,
                headers={"Accept": "application/sparql-results+json", "User-Agent": WIKI_UA},
            )
            with urllib.request.urlopen(req, timeout=120, context=SSL_CONTEXT) as resp:
                return json.loads(resp.read().decode("utf-8"))["results"]["bindings"]
        except Exception as err:  # noqa: BLE001
            if attempt == retries:
                raise RuntimeError(f"SPARQL failed: {err}") from err
    return []

